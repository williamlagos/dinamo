#include "BitmapFont.hpp"

#include <cctype>
#include <cstdint>

namespace dinamo {

namespace {

// Compact 4x5 uppercase bitmap glyph rows (4 bits per row, MSB = left pixel)
struct Glyph {
    uint8_t rows[5];
};

Glyph glyphFor(char c) {
    c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    switch (c) {
        case '0': return {{0x6, 0x9, 0x9, 0x9, 0x6}};
        case '1': return {{0x2, 0x6, 0x2, 0x2, 0x7}};
        case '2': return {{0x6, 0x9, 0x2, 0x4, 0xF}};
        case '3': return {{0xE, 0x1, 0x6, 0x1, 0xE}};
        case '4': return {{0x9, 0x9, 0xF, 0x1, 0x1}};
        case '5': return {{0xF, 0x8, 0xE, 0x1, 0xE}};
        case '6': return {{0x6, 0x8, 0xE, 0x9, 0x6}};
        case '7': return {{0xF, 0x1, 0x2, 0x4, 0x4}};
        case '8': return {{0x6, 0x9, 0x6, 0x9, 0x6}};
        case '9': return {{0x6, 0x9, 0x7, 0x1, 0x6}};
        case 'A': return {{0x6, 0x9, 0xF, 0x9, 0x9}};
        case 'B': return {{0xE, 0x9, 0xE, 0x9, 0xE}};
        case 'C': return {{0x7, 0x8, 0x8, 0x8, 0x7}};
        case 'D': return {{0xE, 0x9, 0x9, 0x9, 0xE}};
        case 'E': return {{0xF, 0x8, 0xE, 0x8, 0xF}};
        case 'F': return {{0xF, 0x8, 0xE, 0x8, 0x8}};
        case 'G': return {{0x7, 0x8, 0xB, 0x9, 0x7}};
        case 'H': return {{0x9, 0x9, 0xF, 0x9, 0x9}};
        case 'I': return {{0x7, 0x2, 0x2, 0x2, 0x7}};
        case 'J': return {{0x1, 0x1, 0x1, 0x9, 0x6}};
        case 'K': return {{0x9, 0xA, 0xC, 0xA, 0x9}};
        case 'L': return {{0x8, 0x8, 0x8, 0x8, 0xF}};
        case 'M': return {{0x9, 0xF, 0xF, 0x9, 0x9}};
        case 'N': return {{0x9, 0xD, 0xB, 0x9, 0x9}};
        case 'O': return {{0x6, 0x9, 0x9, 0x9, 0x6}};
        case 'P': return {{0xE, 0x9, 0xE, 0x8, 0x8}};
        case 'Q': return {{0x6, 0x9, 0x9, 0xB, 0x7}};
        case 'R': return {{0xE, 0x9, 0xE, 0xA, 0x9}};
        case 'S': return {{0x7, 0x8, 0x6, 0x1, 0xE}};
        case 'T': return {{0xF, 0x4, 0x4, 0x4, 0x4}};
        case 'U': return {{0x9, 0x9, 0x9, 0x9, 0x6}};
        case 'V': return {{0x9, 0x9, 0x9, 0x6, 0x6}};
        case 'W': return {{0x9, 0x9, 0xF, 0xF, 0x9}};
        case 'X': return {{0x9, 0x6, 0x6, 0x6, 0x9}};
        case 'Y': return {{0x9, 0x9, 0x6, 0x2, 0x2}};
        case 'Z': return {{0xF, 0x2, 0x4, 0x8, 0xF}};
        case ':': return {{0x0, 0x4, 0x0, 0x4, 0x0}};
        case '-': return {{0x0, 0x0, 0xE, 0x0, 0x0}};
        case '[': return {{0x6, 0x4, 0x4, 0x4, 0x6}};
        case ']': return {{0x6, 0x2, 0x2, 0x2, 0x6}};
        case '/': return {{0x1, 0x2, 0x2, 0x4, 0x8}};
        case '.': return {{0x0, 0x0, 0x0, 0x0, 0x4}};
        case '!': return {{0x4, 0x4, 0x4, 0x0, 0x4}};
        default:  return {{0x0, 0x0, 0x0, 0x0, 0x0}};
    }
}

} // namespace

int BitmapFont::measureWidth(const std::string& text, int scale) {
    if (text.empty()) return 0;
    return static_cast<int>(text.size()) * (5 * scale) - scale;
}

void BitmapFont::drawText(
    SDL_Renderer* renderer,
    const std::string& text,
    int x,
    int y,
    RGBA color,
    int scale,
    bool centered,
    int areaWidth
) {
    if (!renderer || text.empty()) return;
    int drawX = centered ? (areaWidth - measureWidth(text, scale)) / 2 : x;

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    for (char c : text) {
        Glyph g = glyphFor(c);
        for (int row = 0; row < 5; ++row) {
            uint8_t bits = g.rows[row];
            for (int col = 0; col < 4; ++col) {
                if (bits & (1u << (3 - col))) {
                    SDL_Rect rect{drawX + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(renderer, &rect);
                }
            }
        }
        drawX += 5 * scale;
    }
}

} // namespace dinamo
